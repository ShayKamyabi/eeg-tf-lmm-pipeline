function lim = display_xlim(P)

    x = P.Displayed_Conflict;
    x = x(isfinite(x));

    xMin = min(x);
    xMax = max(x);
    xr = xMax-xMin;

    if ~isfinite(xr) || xr <= 0
        xr = 1;
    end

    lim = [xMin-0.055*xr xMax+0.055*xr];
end

