function P = make_prediction_points( ...
    lmm,baseData,groupName,zsv_levels,conflict_display, ...
    beta_levels,beta_labels)

    nPoints = numel(zsv_levels);
    nBeta = numel(beta_levels);
    blocks = cell(nBeta,1);
    cats = categories(baseData.CC_Group);

    for j = 1:nBeta

        New = baseData(repmat(1,nPoints,1),:);

        New.Z_Abs_SV = zsv_levels;
        New.Z_Neural_Braking = repmat(beta_levels(j),nPoints,1);

        New.CC_Group = categorical( ...
            repmat(groupName,nPoints,1), ...
            cats);

        [pred_log,ci_log] = predict( ...
            lmm,New, ...
            'Conditional',false);

        pred_rt  = exp(pred_log);
        lower_rt = exp(ci_log(:,1));
        upper_rt = exp(ci_log(:,2));

        err_low  = pred_rt-lower_rt;
        err_high = upper_rt-pred_rt;

        blocks{j} = table( ...
            repmat(groupName,nPoints,1), ...
            repmat(beta_levels(j),nPoints,1), ...
            repmat(beta_labels(j),nPoints,1), ...
            zsv_levels, ...
            conflict_display, ...
            pred_log, ...
            ci_log(:,1), ...
            ci_log(:,2), ...
            pred_rt, ...
            lower_rt, ...
            upper_rt, ...
            err_low, ...
            err_high, ...
            'VariableNames',{ ...
            'CC_Group', ...
            'Z_Beta_Modulation', ...
            'Beta_Label', ...
            'Z_Abs_SV', ...
            'Displayed_Conflict', ...
            'Predicted_LogRT', ...
            'Lower_LogRT', ...
            'Upper_LogRT', ...
            'Predicted_RT', ...
            'Lower_RT', ...
            'Upper_RT', ...
            'Err_Low', ...
            'Err_High'});
    end

    P = vertcat(blocks{:});
end

function T = audit_prediction_direction(P,groupName)

    betaLevels = [-1 1];
    betaNames = [ ...
        "Stronger suppression (-1 SD)"; ...
        "Weaker suppression (+1 SD)"];

    delta = NaN(2,1);
    leftRT = NaN(2,1);
    rightRT = NaN(2,1);
    leftX = NaN(2,1);
    rightX = NaN(2,1);

    for j = 1:2

        S = P(abs(P.Z_Beta_Modulation-betaLevels(j)) < 1e-12,:);
        [~,ord] = sort(S.Displayed_Conflict,'ascend');
        S = S(ord,:);

        leftX(j) = S.Displayed_Conflict(1);
        rightX(j) = S.Displayed_Conflict(end);
        leftRT(j) = S.Predicted_RT(1);
        rightRT(j) = S.Predicted_RT(end);
        delta(j) = rightRT(j)-leftRT(j);
    end

    T = table( ...
        repmat(groupName,2,1), ...
        betaNames, ...
        leftX,rightX,leftRT,rightRT,delta, ...
        'VariableNames',{ ...
        'CC_Group','Beta_Level', ...
        'Left_Conflict','Right_Conflict', ...
        'Left_RT','Right_RT', ...
        'Delta_RT_RightMinusLeft'});
end

