function draw_horizontal_forest( ...
    ax,labels,est,lo,hi,pvals,colors,colGrid,colZero,colText,fontName)

    hold(ax,'on');

    n = numel(labels);
    y = 1:n;
    set(ax,'YDir','reverse');

    allDataX = [lo(:);hi(:);est(:);0];
    xDataMin = min(allDataX);
    xDataMax = max(allDataX);
    rawSpan = xDataMax-xDataMin;

    if ~isfinite(rawSpan) || rawSpan <= 0
        rawSpan = 1;
    end

    dataPad = 0.12*rawSpan;
    xDataMin = xDataMin-dataPad;
    xDataMax = xDataMax+dataPad;

    pZoneWidth = 0.34*rawSpan;
    xFullMax = xDataMax+pZoneWidth;

    xline( ...
        ax,0,'--', ...
        'Color',colZero, ...
        'LineWidth',0.9, ...
        'HandleVisibility','off');

    plot( ...
        ax,[xDataMax xDataMax],[0.55 n+0.45], ...
        ':', ...
        'Color',[0.84 0.84 0.84], ...
        'LineWidth',0.8, ...
        'HandleVisibility','off');

    for i = 1:n

        plot( ...
            ax,[lo(i) hi(i)],[y(i) y(i)], ...
            '-', ...
            'Color',colors(i,:), ...
            'LineWidth',2.1, ...
            'HandleVisibility','off');

        plot( ...
            ax,[lo(i) lo(i)],[y(i)-0.075 y(i)+0.075], ...
            '-', ...
            'Color',colors(i,:), ...
            'LineWidth',1.1, ...
            'HandleVisibility','off');

        plot( ...
            ax,[hi(i) hi(i)],[y(i)-0.075 y(i)+0.075], ...
            '-', ...
            'Color',colors(i,:), ...
            'LineWidth',1.1, ...
            'HandleVisibility','off');

        scatter( ...
            ax,est(i),y(i),58, ...
            'MarkerFaceColor',colors(i,:), ...
            'MarkerEdgeColor',[1 1 1], ...
            'LineWidth',0.9, ...
            'HandleVisibility','off');

        if pvals(i) < 0.001
            ptxt = 'p < .001';
        else
            ptxt = sprintf('p = %.3f',pvals(i));
        end

        text( ...
            ax, ...
            xDataMax+0.12*pZoneWidth, ...
            y(i), ...
            ptxt, ...
            'HorizontalAlignment','left', ...
            'VerticalAlignment','middle', ...
            'FontName',fontName, ...
            'FontSize',8.4, ...
            'Color',colText, ...
            'Clipping','on');
    end

    xlim(ax,[xDataMin xFullMax]);
    ylim(ax,[0.55 n+0.45]);

    tickMin = floor(xDataMin*10)/10;
    tickMax = ceil(xDataMax*10)/10;

    if tickMax <= tickMin
        tickMax = tickMin+1;
    end

    xTicks = unique(round(linspace(tickMin,tickMax,4),2));

    set( ...
        ax, ...
        'XTick',xTicks, ...
        'YTick',y, ...
        'YTickLabel',labels, ...
        'FontName',fontName, ...
        'FontSize',10, ...
        'LineWidth',0.9, ...
        'TickDir','out', ...
        'TickLength',[0.015 0.015], ...
        'Box','off', ...
        'Layer','top', ...
        'XGrid','on', ...
        'YGrid','off', ...
        'GridColor',colGrid, ...
        'GridAlpha',0.34, ...
        'XColor',[0.22 0.22 0.22], ...
        'YColor',[0.22 0.22 0.22]);
end

function [R2_fixed,R2_full] = prediction_r2(lmm,D)

    y = D.Log_RT;
    SST = sum((y-mean(y)).^2);

    y_fixed = predict(lmm,D,'Conditional',false);
    y_full = predict(lmm,D,'Conditional',true);

    R2_fixed = 1-sum((y-y_fixed).^2)/SST;
    R2_full = 1-sum((y-y_full).^2)/SST;
end

function terms = get_anova_terms(A)

    try
        terms = string(A.Term);
        terms = strip(terms(:));

        if ~isempty(terms)
            return;
        end
    catch
    end

    if istable(A) && ~isempty(A.Properties.RowNames)
        terms = string(A.Properties.RowNames);
        terms = strip(terms(:));
        return;
    end

    error('Could not determine ANOVA term names.');
end

function idx = find_effect_term(terms,required_vars)

    terms = string(terms(:));

    normalized = erase( ...
        terms, ...
        [" ","(",")","{","}","'"]);

    mask = true(size(normalized));

    for k = 1:numel(required_vars)
        mask = mask & contains( ...
            normalized, ...
            string(required_vars{k}));
    end

    strictMask = ...
        mask & ...
        count(normalized,":") == (numel(required_vars)-1);

    idx = find(strictMask);

    if numel(idx) ~= 1
        idx = find(mask);
    end

    if numel(idx) ~= 1
        fprintf('\nAvailable model terms:\n');
        disp(terms);
        error('Could not uniquely identify requested model effect.');
    end
end

function S = extract_effect_stats(lmm,A,required_vars)

    anova_terms = get_anova_terms(A);
    aidx = find_effect_term(anova_terms,required_vars);

    C = lmm.Coefficients;
    coef_terms = string(C.Name);
    cidx = find_effect_term(coef_terms,required_vars);

    S = struct();

    S.AnovaTerm = anova_terms(aidx);
    S.CoefTerm = coef_terms(cidx);

    S.Estimate = double(C.Estimate(cidx));
    S.SE = double(C.SE(cidx));
    S.Lower = double(C.Lower(cidx));
    S.Upper = double(C.Upper(cidx));

    S.FStat = double(A.FStat(aidx));
    S.DF1 = double(A.DF1(aidx));
    S.DF2 = double(A.DF2(aidx));
    S.pValue = double(A.pValue(aidx));
end

function export_one_figure(fig,out_dir,baseName,w_cm,h_cm)

    drawnow;
    pause(0.15);

    if ~exist(out_dir,'dir')
        mkdir(out_dir);
    end

    fig_file = fullfile(out_dir,[baseName '.fig']);
    pdf_file = fullfile(out_dir,[baseName '.pdf']);
    eps_file = fullfile(out_dir,[baseName '.eps']);
    png_file = fullfile(out_dir,[baseName '.png']);
    tif_file = fullfile(out_dir,[baseName '.tif']);
    svg_file = fullfile(out_dir,[baseName '.svg']);

    safe_delete(pdf_file);
    safe_delete(eps_file);
    safe_delete(png_file);
    safe_delete(tif_file);
    safe_delete(svg_file);

    savefig(fig,fig_file);

    set(fig,'PaperUnits','centimeters');
    set(fig,'PaperSize',[w_cm h_cm]);
    set(fig,'PaperPosition',[0 0 w_cm h_cm]);
    set(fig,'PaperPositionMode','manual');
    set(fig,'InvertHardcopy','off');

    print(fig,pdf_file,'-dpdf','-painters');
    print(fig,eps_file,'-depsc','-painters');

    temp_png = fullfile(tempdir,[baseName '__temp.png']);
    temp_tif = fullfile(tempdir,[baseName '__temp.tif']);

    safe_delete(temp_png);
    safe_delete(temp_tif);

    try
        exportgraphics( ...
            fig,temp_png, ...
            'Resolution',600, ...
            'BackgroundColor','white');

        [ok,msg] = copyfile(temp_png,png_file,'f');
        if ~ok
            warning('Could not copy PNG: %s',msg);
        end
    catch ME
        warning('PNG export failed: %s',ME.message);
    end

    try
        exportgraphics( ...
            fig,temp_tif, ...
            'Resolution',600, ...
            'BackgroundColor','white');

        [ok,msg] = copyfile(temp_tif,tif_file,'f');
        if ~ok
            warning('Could not copy TIFF: %s',msg);
        end
    catch ME
        warning('TIFF export failed: %s',ME.message);
    end

    safe_delete(temp_png);
    safe_delete(temp_tif);

    try
        exportgraphics( ...
            fig,svg_file, ...
            'ContentType','vector', ...
            'BackgroundColor','white');
    catch ME
        warning('SVG export skipped/failed: %s',ME.message);
    end

    fprintf('\nExported: %s\n',baseName);
end

function safe_delete(filePath)

    if isfile(filePath)
        try
            delete(filePath);
        catch
            warning('Could not delete existing file: %s',filePath);
        end
    end
end
